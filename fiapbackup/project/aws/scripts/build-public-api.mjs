import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const repoRoot = path.resolve(__dirname, '..', '..')
const entryPoint = path.join(repoRoot, 'backend', 'cloud', 'handlers', 'publicApi.ts')
const outputDir = path.join(repoRoot, 'aws', 'dist', 'public-api')
const outputFile = path.join(outputDir, 'index.mjs')

await mkdir(outputDir, { recursive: true })

await build({
  entryPoints: [entryPoint],
  outfile: outputFile,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: false,
  minify: false,
  banner: {
    js: '// Generated by aws/scripts/build-public-api.mjs',
  },
})

console.log(outputFile)
